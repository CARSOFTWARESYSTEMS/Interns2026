// ── Link-preview metadata per login domain (in the served HTML) ────────────
//
// WhatsApp, LinkedIn, Slack and other link-preview crawlers never run the
// app's JavaScript, so theme.ts's runtime title and favicon are invisible to
// them. They read the HTML the server returns for the host instead:
//
//   • index.html carries neutral tags between the social-meta markers.
//   • At build time vite.config.ts writes index.<partnerId>.html, a copy with
//     that Partner's tags (socialMetaFor + renderSocialMeta) between them.
//   • vercel.json serves the Partner's copy for "/" on its login domains;
//     every other host gets the neutral index.html.
//
// Copy comes from partners.seed.json (build time), not Firestore. Images are
// generated by scripts/generate-partner-images.py into public/partners/<id>/.

import type { Partner } from '../types/partner'
import { brandingFor, escapeHtml, safeUrl } from './branding'
import { parseHex } from './theme'

export const SOCIAL_META_START = '<!-- social-meta:start -->'
export const SOCIAL_META_END = '<!-- social-meta:end -->'

export const OG_IMAGE_WIDTH = 1200
export const OG_IMAGE_HEIGHT = 630

export interface SocialMeta {
  /** <title>, og:title and twitter:title; matches document.title once theme.ts runs. */
  title: string
  siteName: string
  /** application-name; matches theme.ts. */
  appName: string
  description: string
  /** Absolute canonical URL ('' when the host is unknown). */
  url: string
  image: string
  imageAlt: string
  themeColor: string
  icon: string
  appleTouchIcon: string
}

