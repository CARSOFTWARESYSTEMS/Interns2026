/** Built file served for a Partner's login domains (see vercel.json). */
export function partnerHtmlFile(partnerId: string): string {
  return `index.${partnerId}.html`
}

/** Static assets generated per Partner (public/partners/<id>/). */
export function partnerAssetDir(partnerId: string): string {
  return `/partners/${partnerId}`
}

export function socialMetaFor(p: Partner): SocialMeta {
  const b = brandingFor(p)
  const origin = `https://${p.defaultDomain}`
  const assets = partnerAssetDir(p.id)
  const subtitle = b.login.subtitle || p.description
  const secondary = p.branding?.secondaryColor ?? ''
  return {
    title: `${b.title} · ${b.tagline}`,
    siteName: b.name,
    appName: b.title,
    description: `${subtitle ? `${subtitle}. ` : ''}Sign in to the ${b.name} ${b.tagline} for intern programs, QA workflows and mission-ready evidence.`,
    url: `${origin}/`,
    image: `${origin}${assets}/og-image.png`,
    imageAlt: subtitle ? `${b.name}: ${subtitle}` : b.name,
    themeColor: parseHex(secondary) ? secondary : '#0f172a',
    icon: b.faviconUrl || `${assets}/icon-96.png`,
    appleTouchIcon: `${assets}/apple-touch-icon.png`,
  }
}

/** The tags that go between the social-meta markers, indented like index.html. */
export function renderSocialMeta(m: SocialMeta): string {
  const e = escapeHtml
  const meta = (attr: 'name' | 'property', key: string, value: string) =>
    `<meta ${attr}="${key}" content="${e(value)}" />`
  const icon = safeUrl(m.icon)
  const tags = [
    `<title>${e(m.title)}</title>`,
    meta('name', 'description', m.description),
    meta('name', 'application-name', m.appName),
    meta('name', 'apple-mobile-web-app-title', m.appName),
    meta('name', 'robots', 'index, follow'),
    meta('name', 'theme-color', m.themeColor),
    m.url && `<link rel="canonical" href="${e(m.url)}" />`,
    icon && `<link rel="icon" sizes="96x96" href="${e(icon)}" />`,
    m.appleTouchIcon && `<link rel="apple-touch-icon" href="${e(m.appleTouchIcon)}" />`,
    meta('property', 'og:type', 'website'),
    meta('property', 'og:site_name', m.siteName),
    meta('property', 'og:title', m.title),
    meta('property', 'og:description', m.description),
    m.url && meta('property', 'og:url', m.url),
    meta('property', 'og:image', m.image),
    meta('property', 'og:image:width', String(OG_IMAGE_WIDTH)),
    meta('property', 'og:image:height', String(OG_IMAGE_HEIGHT)),
    meta('property', 'og:image:alt', m.imageAlt),
    meta('name', 'twitter:card', 'summary_large_image'),
    meta('name', 'twitter:title', m.title),
    meta('name', 'twitter:description', m.description),
    meta('name', 'twitter:image', m.image),
    meta('name', 'twitter:image:alt', m.imageAlt),
  ]
  return tags.filter(Boolean).map(t => `    ${t}`).join('\n')
}

/** Replace the neutral block in index.html with `tags`; throws if the markers are missing. */
export function withSocialMeta(html: string, tags: string): string {
  const start = html.indexOf(SOCIAL_META_START)
  const end = html.indexOf(SOCIAL_META_END)
  if (start === -1 || end < start || html.indexOf(SOCIAL_META_START, start + 1) !== -1) {
    throw new Error('index.html must contain exactly one social-meta:start … social-meta:end block')
  }
  return `${html.slice(0, start + SOCIAL_META_START.length)}\n${tags}\n    ${html.slice(end)}`
}
